/**
 * Emit `src/ai/tools/api/endpointIndex.gen.ts` from the OpenAPI spec: every GET endpoint of
 * the v3 API with its filters, compact enough for the assistant to search in the browser.
 * Paths are relative to `api/v3/`; one under an href is written `{href}<suffix>`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "openapi/pulp.json"), "utf8"));

const V3_PREFIX = /^\/api\/pulp\/(\{pulp_domain\}\/)?api\/v3\//;
const HREF_PATH = /^\{\w+_href\}(.*)$/;
// Every list takes these; the tool explains them once.
const COMMON = new Set([
  "limit",
  "offset",
  "fields",
  "exclude_fields",
  "ordering",
  "pulp_domain",
]);

const firstSentence = (text = "") =>
  text
    .replace(/\s+/g, " ")
    .trim()
    .split(/(?<=\.)\s/)[0]
    .slice(0, 90);

const entries = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  if (!item.get) continue;
  // Object paths are written `{<type>_href}<suffix>`, without the API prefix.
  const href = HREF_PATH.exec(path);
  const prefix = V3_PREFIX.exec(path);
  if (!href && !prefix) continue;
  const endpoint = href ? `{href}${href[1]}` : path.slice(prefix[0].length);
  if (endpoint.slice(endpoint.startsWith("{href}") ? 6 : 0).includes("{"))
    continue;
  const filters = (item.get.parameters ?? [])
    .filter((parameter) => parameter.in === "query")
    .map((parameter) => parameter.name)
    .filter((name) => !COMMON.has(name));
  const previous = entries.get(endpoint);
  entries.set(endpoint, {
    path: endpoint,
    summary: href
      ? (previous?.summary ??
        `${href[1] ? firstSentence(item.get.summary) : "Read one object"} (any pulp_href)`)
      : (previous?.summary ??
        firstSentence(item.get.summary ?? item.get.description)),
    filters: [...new Set([...(previous?.filters ?? []), ...filters])],
    outsideDomain: !href && !prefix[1],
  });
}

const sorted = [...entries.values()].sort((a, b) =>
  a.path.localeCompare(b.path),
);
const lines = sorted.map(
  ({ path, summary, filters, outsideDomain }) =>
    `  [${JSON.stringify(path)}, ${JSON.stringify(summary)}, ${JSON.stringify(filters.join(" "))}${outsideDomain ? ", true" : ""}],`,
);
writeFileSync(
  join(root, "src/ai/tools/api/endpointIndex.gen.ts"),
  `// Generated by scripts/generate-ai-endpoint-index.mjs from openapi/pulp.json. Do not edit.
/** [path relative to api/v3/, summary, space-separated filters, outside any domain]. */
export type EndpointEntry = readonly [string, string, string, true?];

export const ENDPOINT_INDEX: readonly EndpointEntry[] = [
${lines.join("\n")}
];
`,
);
console.log(`${sorted.length} GET endpoints`);
