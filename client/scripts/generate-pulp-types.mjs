/**
 * Emit `src/app/client/pulpTypes.gen.ts`: for each plugin collection in the OpenAPI spec
 * (`<entity>/<app>/<slug>/`), the generated request and list types its operations use, keyed
 * by the `<app>/<slug>` apiPath. Plugin definitions type their `apiPath` against these maps,
 * so a path the API doesn't have fails to compile and forms find their body type by path.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(
  readFileSync(join(root, "openapi/pulp.json"), "utf8"),
);
const target = join(root, "src/app/client/pulpTypes.gen.ts");

const COLLECTION =
  /^\/api\/pulp\/\{pulp_domain\}\/api\/v3\/(remotes|repositories|distributions|publications|content|acs)\/([^/{}]+)\/([^/{}]+)\/$/;

// How @hey-api/openapi-ts names an operation's types: PascalCase of the operationId.
const typeName = (operationId) =>
  operationId
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

// Detail paths are bare href params (`/{rpm_uln_remote_href}`), so the partial update is
// found by its operationId: the collection's list operation with `_partial_update`.
const operationIds = new Set(
  Object.values(spec.paths).flatMap((item) =>
    Object.values(item).flatMap((op) => (op?.operationId ? [op.operationId] : [])),
  ),
);
const patchOperation = (listOperationId) => {
  const id = listOperationId?.replace(/_list$/, "_partial_update");
  return id && operationIds.has(id) ? id : undefined;
};

const maps = {
  remotes: [],
  repositories: [],
  distributions: [],
  publications: [],
  content: [],
  acs: [],
};
const imports = new Set();

for (const [path, item] of Object.entries(spec.paths)) {
  const match = COLLECTION.exec(path);
  if (!match) continue;
  const [, collection, app, slug] = match;
  const apiPath = `${app}/${slug}`;
  const members = [];
  if (collection === "content") {
    const list = item.get?.operationId;
    if (!list) continue;
    imports.add(`${typeName(list)}Data`).add(`${typeName(list)}Response`);
    members.push(`list: ${typeName(list)}Data`);
    members.push(`page: ${typeName(list)}Response`);
  } else {
    const create = item.post?.operationId;
    const patch = patchOperation(item.get?.operationId);
    if (create) {
      imports.add(`${typeName(create)}Data`);
      members.push(`create: ${typeName(create)}Data["body"]`);
    }
    if (patch) {
      imports.add(`${typeName(patch)}Data`);
      members.push(`update: NonNullable<${typeName(patch)}Data["body"]>`);
    }
  }
  maps[collection].push(`  "${apiPath}": { ${members.join("; ")} };`);
}

const block = (name, doc, rows) =>
  `/** ${doc} */\nexport interface ${name} {\n${rows.sort().join("\n")}\n}\n`;

const source = `// Generated by scripts/generate-pulp-types.mjs from openapi/pulp.json. Do not edit.
import type {
${[...imports]
  .sort()
  .map((name) => `  ${name},`)
  .join("\n")}
} from "./types.gen";

${block("RemoteEndpoints", "Remote collections by apiPath: create and update bodies.", maps.remotes)}
${block("RepositoryEndpoints", "Repository collections by apiPath: create and update bodies.", maps.repositories)}
${block("DistributionEndpoints", "Distribution collections by apiPath: create and update bodies.", maps.distributions)}
${block("PublicationEndpoints", "Publication collections by apiPath: the create body.", maps.publications)}
${block("ContentEndpoints", "Content collections by apiPath: list params and page.", maps.content)}
${block("AcsEndpoints", "Alternate content source collections by apiPath: create and update bodies.", maps.acs)}`;

writeFileSync(target, source);
console.log(`generate-pulp-types: wrote ${target}`);
